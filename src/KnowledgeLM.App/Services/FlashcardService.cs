using System.ComponentModel;
using System.Text.Json;
using KnowledgeLM.App.Data;
using KnowledgeLM.App.Models.AI;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;
using Microsoft.SemanticKernel;

namespace KnowledgeLM.App.Services;

/// <summary>
/// Service for generating and managing AI-generated flashcards from notebook resources.
/// </summary>
public class FlashcardService
{
    private readonly IDbContextFactory<NotesContext> _contextFactory;
    private readonly NotesCRUDService _notesCrudService;
    private readonly ILogger<FlashcardService> _logger;

    public FlashcardService(
        IDbContextFactory<NotesContext> contextFactory,
        NotesCRUDService notesCrudService,
        ILogger<FlashcardService> logger)
    {
        _contextFactory = contextFactory;
        _notesCrudService = notesCrudService;
        _logger = logger;
    }

    /// <summary>
    /// Get all flashcards for a resource.
    /// </summary>
    [KernelFunction("get_flashcards")]
    [Description("Gets all flashcards for a given resource ID.")]
    public async Task<List<Flashcard>> GetFlashcardsByResourceIdAsync(int resourceId)
    {
        await using var context = await _contextFactory.CreateDbContextAsync();
        return await context.Flashcards
            .AsNoTracking()
            .Where(f => f.ResourceId == resourceId)
            .OrderBy(f => f.Id)
            .ToListAsync();
    }

    /// <summary>
    /// Check if flashcards exist for a resource.
    /// </summary>
    public async Task<bool> HasFlashcardsAsync(int resourceId)
    {
        await using var context = await _contextFactory.CreateDbContextAsync();
        return await context.Flashcards.AnyAsync(f => f.ResourceId == resourceId);
    }

    /// <summary>
    /// Get the count of flashcards for a resource.
    /// </summary>
    public async Task<int> GetFlashcardCountAsync(int resourceId)
    {
        await using var context = await _contextFactory.CreateDbContextAsync();
        return await context.Flashcards.CountAsync(f => f.ResourceId == resourceId);
    }

    /// <summary>
    /// Save flashcards generated by the AI agent for a resource.
    /// </summary>
    [KernelFunction("save_flashcards")]
    [Description("Saves a list of flashcard Q&A pairs for a resource. Input is a JSON array of objects with 'question' and 'answer' fields.")]
    public async Task<int> SaveFlashcardsAsync(int resourceId, string flashcardsJson)
    {
        try
        {
            var items = JsonSerializer.Deserialize<List<FlashcardItem>>(flashcardsJson, new JsonSerializerOptions
            {
                PropertyNameCaseInsensitive = true
            });

            if (items is null || items.Count == 0)
                return 0;

            await using var context = await _contextFactory.CreateDbContextAsync();

            foreach (var item in items)
            {
                context.Flashcards.Add(new Flashcard
                {
                    ResourceId = resourceId,
                    Question = item.Question,
                    Answer = item.Answer
                });
            }

            await context.SaveChangesAsync();
            _logger.LogInformation("Saved {Count} flashcards for resource {ResourceId}.", items.Count, resourceId);
            return items.Count;
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Failed to save flashcards for resource {ResourceId}.", resourceId);
            return 0;
        }
    }

    /// <summary>
    /// Delete all flashcards for a resource.
    /// </summary>
    public async Task DeleteFlashcardsForResourceAsync(int resourceId)
    {
        await using var context = await _contextFactory.CreateDbContextAsync();
        var flashcards = await context.Flashcards
            .Where(f => f.ResourceId == resourceId)
            .ToListAsync();

        if (flashcards.Count > 0)
        {
            context.Flashcards.RemoveRange(flashcards);
            await context.SaveChangesAsync();
            _logger.LogInformation("Deleted {Count} flashcards for resource {ResourceId}.", flashcards.Count, resourceId);
        }
    }

    /// <summary>
    /// Reads the content of a resource file for flashcard generation context.
    /// </summary>
    public async Task<string?> GetResourceContentAsync(int resourceId)
    {
        var resource = await _notesCrudService.GetResourceByIdAsync(resourceId);
        if (resource is null || string.IsNullOrWhiteSpace(resource.Location))
            return null;

        if (!File.Exists(resource.Location))
            return null;

        return await File.ReadAllTextAsync(resource.Location);
    }

    private class FlashcardItem
    {
        public string Question { get; set; } = string.Empty;
        public string Answer { get; set; } = string.Empty;
    }
}
