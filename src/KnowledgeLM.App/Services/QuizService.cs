using System.ComponentModel;
using System.Text.Json;
using KnowledgeLM.App.Data;
using KnowledgeLM.App.Models.AI;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;
using Microsoft.SemanticKernel;

namespace KnowledgeLM.App.Services;

/// <summary>
/// Service for generating and managing AI-generated quizzes from notebook resources.
/// </summary>
public class QuizService
{
    private readonly IDbContextFactory<NotesContext> _contextFactory;
    private readonly NotesCRUDService _notesCrudService;
    private readonly ILogger<QuizService> _logger;
    private readonly AppNotificationService _notifications;

    public QuizService(
        IDbContextFactory<NotesContext> contextFactory,
        NotesCRUDService notesCrudService,
        ILogger<QuizService> logger,
        AppNotificationService notifications)
    {
        _contextFactory = contextFactory;
        _notesCrudService = notesCrudService;
        _logger = logger;
        _notifications = notifications;
    }

    /// <summary>
    /// Get all quiz questions for a resource.
    /// </summary>
    [KernelFunction("get_quizzes")]
    [Description("Gets all quiz questions for a given resource ID.")]
    public async Task<List<Quiz>> GetQuizzesByResourceIdAsync(int resourceId)
    {
        await using var context = await _contextFactory.CreateDbContextAsync();
        return await context.Quizzes
            .AsNoTracking()
            .Where(q => q.ResourceId == resourceId)
            .OrderBy(q => q.Id)
            .ToListAsync();
    }

    /// <summary>
    /// Check if quizzes exist for a resource.
    /// </summary>
    public async Task<bool> HasQuizzesAsync(int resourceId)
    {
        await using var context = await _contextFactory.CreateDbContextAsync();
        return await context.Quizzes.AnyAsync(q => q.ResourceId == resourceId);
    }

    /// <summary>
    /// Get the count of quizzes for a resource.
    /// </summary>
    public async Task<int> GetQuizCountAsync(int resourceId)
    {
        await using var context = await _contextFactory.CreateDbContextAsync();
        return await context.Quizzes.CountAsync(q => q.ResourceId == resourceId);
    }

    /// <summary>
    /// Save quiz questions generated by the AI agent for a resource.
    /// </summary>
    [KernelFunction("save_quizzes")]
    [Description("Saves a list of multiple-choice quiz questions for a resource. Input is a JSON array of objects with 'question' (string), 'options' (string array of 4 choices), 'correctOptionIndex' (zero-based int), and 'explanation' (string) fields.")]
    public async Task<int> SaveQuizzesAsync(int resourceId, string quizzesJson)
    {
        try
        {
            var items = JsonSerializer.Deserialize<List<QuizItem>>(quizzesJson, new JsonSerializerOptions
            {
                PropertyNameCaseInsensitive = true
            });

            if (items is null || items.Count == 0)
                return 0;

            await using var context = await _contextFactory.CreateDbContextAsync();

            foreach (var item in items)
            {
                context.Quizzes.Add(new Quiz
                {
                    ResourceId = resourceId,
                    Question = item.Question,
                    OptionsJson = JsonSerializer.Serialize(item.Options),
                    CorrectOptionIndex = item.CorrectOptionIndex,
                    Explanation = item.Explanation
                });
            }

            await context.SaveChangesAsync();
            _logger.LogInformation("Saved {Count} quiz questions for resource {ResourceId}.", items.Count, resourceId);
            _notifications.NotifySuccess($"Saved {items.Count} quiz questions.");
            return items.Count;
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Failed to save quizzes for resource {ResourceId}.", resourceId);
            _notifications.NotifyError($"Failed to save quizzes: {ex.Message}");
            return 0;
        }
    }

    /// <summary>
    /// Delete all quizzes for a resource.
    /// </summary>
    public async Task DeleteQuizzesForResourceAsync(int resourceId)
    {
        await using var context = await _contextFactory.CreateDbContextAsync();
        var quizzes = await context.Quizzes
            .Where(q => q.ResourceId == resourceId)
            .ToListAsync();

        if (quizzes.Count > 0)
        {
            context.Quizzes.RemoveRange(quizzes);
            await context.SaveChangesAsync();
            _logger.LogInformation("Deleted {Count} quizzes for resource {ResourceId}.", quizzes.Count, resourceId);
        }
    }

    private class QuizItem
    {
        public string Question { get; set; } = string.Empty;
        public List<string> Options { get; set; } = [];
        public int CorrectOptionIndex { get; set; }
        public string? Explanation { get; set; }
    }
}
